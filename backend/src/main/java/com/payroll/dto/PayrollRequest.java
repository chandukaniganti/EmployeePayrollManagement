
package com.payroll.dto;

public class PayrollRequest {

    private Long employeeId;
    private Integer payrollMonth;
    private Integer payrollYear;

    private Double hra = 0.0;
    private Double da = 0.0;
    private Double otherAllowances = 0.0;

    private Double pf = 0.0;
    private Double esi = 0.0;
    private Double otherDeductions = 0.0;

    public Long getEmployeeId() {
        return employeeId;
    }

    public void setEmployeeId(Long employeeId) {
        this.employeeId = employeeId;
    }

    public Integer getPayrollMonth() {
        return payrollMonth;
    }

    public void setPayrollMonth(Integer payrollMonth) {
        this.payrollMonth = payrollMonth;
    }

    public Integer getPayrollYear() {
        return payrollYear;
    }

    public void setPayrollYear(Integer payrollYear) {
        this.payrollYear = payrollYear;
    }

    public Double getHra() {
        return hra;
    }

    public void setHra(Double hra) {
        this.hra = hra;
    }

    public Double getDa() {
        return da;
    }

    public void setDa(Double da) {
        this.da = da;
    }

    public Double getOtherAllowances() {
        return otherAllowances;
    }

    public void setOtherAllowances(Double otherAllowances) {
        this.otherAllowances = otherAllowances;
    }

    public Double getPf() {
        return pf;
    }

    public void setPf(Double pf) {
        this.pf = pf;
    }

    public Double getEsi() {
        return esi;
    }

    public void setEsi(Double esi) {
        this.esi = esi;
    }

    public Double getOtherDeductions() {
        return otherDeductions;
    }

    public void setOtherDeductions(Double otherDeductions) {
        this.otherDeductions = otherDeductions;
    }
}
